"""IPv4 -> ASN, organization and country lookup backed by a bundled table.

The bundled table is generated by ``tests/gen_geoip.py`` from the
iptoasn.com ip2asn-v4 feed. Ranges are stored as sorted integer bounds so a
lookup is a single bisect plus a bounds check, safe to call on the capture
thread after the one-time load.
"""

from __future__ import annotations

import gzip
import ipaddress
import os
import threading
from bisect import bisect_right

DATA_PATH = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "data", "ip2asn-v4.tsv.gz")

_lock = threading.Lock()
_starts: list[int] | None = None
_ends: list[int] | None = None
_meta: list[tuple[int, str | None, str | None]] | None = None
_failed = False


def _text(value: str) -> str | None:
    value = value.strip()
    return None if value in ("", "None") else value


def load() -> tuple[list[int], list[int], list[tuple[int, str | None, str | None]]] | None:
    global _starts, _ends, _meta, _failed
    if _starts is not None:
        return _starts, _ends, _meta
    if _failed:
        return None
    with _lock:
        if _starts is not None:
            return _starts, _ends, _meta
        if _failed:
            return None
        starts: list[int] = []
        ends: list[int] = []
        meta: list[tuple[int, str | None, str | None]] = []
        try:
            with gzip.open(DATA_PATH, "rt", encoding="utf-8", errors="replace") as fh:
                for line in fh:
                    if not line or line.startswith("#"):
                        continue
                    fields = line.rstrip("\n").split("\t")
                    if len(fields) < 5:
                        continue
                    try:
                        start = int(fields[0])
                        end = int(fields[1])
                        asn = int(fields[2])
                    except ValueError:
                        continue
                    starts.append(start)
                    ends.append(end)
                    meta.append((asn, _text(fields[4]), _text(fields[3])))
        except (OSError, EOFError, ValueError):
            _failed = True
            return None
        _starts, _ends, _meta = starts, ends, meta
        return _starts, _ends, _meta


def _lookup_v6(addr) -> None:
    """Hook for a future ip2asn-v6 table; IPv6 is intentionally unresolved."""
    return None


def lookup(ip: str | None) -> tuple[int, str | None, str | None] | None:
    """Return ``(asn, org, country)`` for an IPv4 address, or ``None``."""
    if not ip:
        return None
    try:
        addr = ipaddress.ip_address(str(ip))
    except ValueError:
        return None
    if addr.version == 6:
        return _lookup_v6(addr)
    table = load()
    if table is None:
        return None
    starts, ends, meta = table
    index = bisect_right(starts, int(addr)) - 1
    if index < 0 or int(addr) > ends[index]:
        return None
    return meta[index]
